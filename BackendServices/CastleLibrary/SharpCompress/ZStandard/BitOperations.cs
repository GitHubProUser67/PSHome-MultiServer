        private static int BitScanReverse11(ulong b) => _msb[b];

        private static byte[] InitNormalizationTable()
        {
            const byte normalizationTableSize = 32;
            var normalizationTable = new byte[normalizationTableSize];
            for (var i = 0; i < normalizationTableSize; i++)
                normalizationTable[i] =
                    i < 9 ? (byte)0
                    : i < 17 ? (byte)8
                    : i < 25 ? (byte)16
                    : (byte)24;
            return normalizationTable;
